export type ReadSchemaSource = {
    text: string;
    statement: CreateSchemaStatement;
    model: SchemaModel;
    statedVersion?: string;
    locate: Locator;
};

function whereOf(file: string, span: TextSpan | undefined): Where | undefined {
    return span === undefined ? undefined : { file, line: span.line, column: span.column };
}

export function readSchemaSource(
    text: string,
    expectedName: string,
    file = SCHEMA_SOURCE_FILE,
    expectedVersion?: string,
): ReadSchemaSource {
    const parsed = parseScript(text);
    if (!parsed.ok) {
        throw new SourceError(parsed.diagnostics.map((d) => ({
            message: d.message,
            ...(d.span !== undefined ? { where: whereOf(file, d.span) } : {}),
        })));
    }
    const script = parsed.value;
    if (script.statements.length === 0) {
        throw new SourceError([{ message: `${file} has no CREATE SCHEMA` }]);
    }
    if (script.statements.length > 1 || script.statements[0].kind !== 'create-schema') {
        const bad = script.statements.find((s) => s.kind !== 'create-schema') ?? script.statements[1]!;
        throw new SourceError([{
            message: `${file} holds a single CREATE SCHEMA statement`,
            where: whereOf(file, bad.span),
        }]);
    }
    const stmt = script.statements[0];
    const issues: SourceIssue[] = [];
    if (!isValidSchemaName(stmt.name)) {
        issues.push({ message: `invalid schema name '${stmt.name}'`, where: whereOf(file, stmt.span) });
    } else if (stmt.name !== expectedName) {
        issues.push({
            message: `${file} creates schema '${stmt.name}', but rpack.json names '${expectedName}'`,
            where: whereOf(file, stmt.span),
        });
    }
    if (stmt.creators.length > 0) {
        issues.push({
            message: `remove CREATORS from ${file}; a reusable schema pack is signed by the catalog that imports it`,
            where: whereOf(file, stmt.span),
        });
    }
    if (stmt.version !== undefined) {
        if (!isValidSemver(stmt.version)) {
            issues.push({ message: `VERSION '${stmt.version}' is not a semver (major.minor.patch)`, where: whereOf(file, stmt.span) });
        } else if (isPatchVersion(stmt.version)) {
            issues.push({ message: `VERSION '${stmt.version}': ${PATCH_VERSION_RESERVED}`, where: whereOf(file, stmt.span) });
        } else if (expectedVersion !== undefined && stmt.version !== expectedVersion) {
            issues.push({
                message: `CREATE SCHEMA: VERSION '${stmt.version}' does not match the release version '${expectedVersion}'`,
                where: whereOf(file, stmt.span),
            });
        }
    }
    if (issues.length > 0) throw new SourceError(issues);

    let params: SchemaParamDecl[];
    const tables = new Map<string, TableDef>();
    try {
        params = compileSchemaParamDecls(stmt.params, false);
        const paramNames = new Set(params.map((p) => p.name));
        const columnsOf = columnsOfFromTableDecls(stmt.tables);
        for (const table of stmt.tables) {
            if (tables.has(table.name)) {
                throw new SourceError([{ message: `duplicate table name '${table.name}'`, where: whereOf(file, table.span) }]);
            }
            const def = compileTable(table, {
                gated: { name: table.name, columns: new Set(table.columns.map((c) => c.name)) },
                columnsOf,
                ...(paramNames.size > 0 ? { params: paramNames } : {}),
            });
            tables.set(table.name, def);
        }
    } catch (err) {
        if (err instanceof SourceError) throw err;
        throw new SourceError([{
            message: err instanceof Error ? err.message : String(err),
            where: whereOf(file, stmt.span),
        }]);
    }

    const units = new Map<string, TextSpan>();
    units.set(unitKey.schema(stmt.name), stmt.span);
    for (const p of stmt.params ?? []) units.set(unitKey.schemaParam(stmt.name, p.name), p.span);
    for (const table of stmt.tables) {
        units.set(unitKey.table(stmt.name, table.name), table.span);
        for (const column of table.columns) units.set(unitKey.column(stmt.name, table.name, column.name), column.span);
    }

    const model: SchemaModel = {
        name: stmt.name,
        creators: [],
        ...(stmt.hashAlgorithm !== undefined ? { hashAlgorithm: stmt.hashAlgorithm } : {}),
        params: new Map(params.map((p) => [p.name, p])),
        tables,
        origin: { kind: 'inline' },
    };

    return {
        text,
        statement: stmt,
        model,
        ...(stmt.version !== undefined ? { statedVersion: stmt.version } : {}),
        locate: (unit) => whereOf(file, units.get(unit)),
    };
}

export type SchemaBaseState = {
    parents: ReleaseInfo[];
    steps: Map<B64Hash, SchemaReleaseStep>;
    view: RSchemaView;
    params: Map<string, SchemaParamDecl>;
    tables: Map<string, TableDef>;
    model: SchemaModel;
};

export class ReleasedSchemas {
    private readonly stepsByHash = new Map<B64Hash, SchemaReleaseStep>();
    private readonly infos = new Map<B64Hash, ReleaseInfo>();

    private constructor(readonly schemaName: string | undefined) {}

    static async open(files: SchemaReleaseFile[], expectedName?: string): Promise<ReleasedSchemas> {
        let name = expectedName;
        const opened = new ReleasedSchemas(name);
        for (const file of files) {
            if (name !== undefined && file.manifest.name !== name) {
                throw new Error(`releases/ holds a release of schema '${file.manifest.name}', not '${name}'`);
            }
            name = file.manifest.name;
            const report = await verifyRelease(file);
            if (!report.ok) {
                throw new Error(`invalid schema release '${file.manifest.name}@${file.manifest.version}': ${report.problems.join('; ')}`);
            }
            for (const step of file.steps) {
                opened.stepsByHash.set(step.hash, step);
            }
        }
        opened.rebuildInfos(name);
        return opened;
    }

    private rebuildInfos(name: string | undefined): void {
        this.infos.clear();
        if (name === undefined) return;
        for (const step of this.stepsByHash.values()) {
            const tag = releaseTag(step.hash);
            const info: ReleaseInfo = {
                hash: step.hash,
                version: step.version,
                tag,
                name: releaseName(name, step.version, step.hash),
                parents: [...step.parents].sort(),
                ...(step.note !== undefined ? { note: step.note } : {}),
            };
            this.infos.set(step.hash, info);
        }
    }

    addStep(name: string, step: SchemaReleaseStep): ReleaseInfo {
        this.stepsByHash.set(step.hash, step);
        const tag = releaseTag(step.hash);
        const info: ReleaseInfo = {
            hash: step.hash,
            version: step.version,
            tag,
            name: releaseName(name, step.version, step.hash),
            parents: [...step.parents].sort(),
            ...(step.note !== undefined ? { note: step.note } : {}),
        };
        this.infos.set(step.hash, info);
        return info;
    }

    releases(): ReleaseInfo[] {
        return sortReleases([...this.infos.values()]);
    }

    get(hash: B64Hash): ReleaseInfo | undefined {
        return this.infos.get(hash);
    }

    step(hash: B64Hash): SchemaReleaseStep | undefined {
        return this.stepsByHash.get(hash);
    }

    resolve(selector: string): ReleaseInfo {
        let text = selector.endsWith('.rpack') ? selector.slice(0, -'.rpack'.length) : selector;
        const slash = text.lastIndexOf('/');
        if (slash !== -1) text = text.slice(slash + 1);
        if (text.startsWith('#')) {
            const matches = this.releases().filter((r) => r.hash.startsWith(text.slice(1)));
            return this.single(selector, matches);
        }
        const prefix = this.schemaName !== undefined ? `${this.schemaName.replace(/:/g, '_')}-` : undefined;
        if (prefix !== undefined && text.startsWith(prefix)) text = text.slice(prefix.length);
        const dash = text.indexOf('-');
        const wanted = dash === -1 ? text : text.slice(0, dash);
        const tag = dash === -1 ? '' : text.slice(dash + 1);
        return this.single(selector, this.releases().filter((r) => r.version === wanted && r.tag.startsWith(tag)));
    }

    private single(selector: string, matches: ReleaseInfo[]): ReleaseInfo {
        if (matches.length === 1) return matches[0];
        if (matches.length === 0) throw new ReleaseSelectionError(`no release matches '${selector}'`);
        throw new ReleaseSelectionError(`'${selector}' matches several releases: ${matches.map((r) => `${r.version}-${r.tag}`).join(', ')}; add the tag`);
    }

    ancestorsOf(hashes: B64Hash[]): Set<B64Hash> {
        const out = new Set<B64Hash>();
        const queue = [...hashes.flatMap((h) => this.stepsByHash.get(h)?.parents ?? [])];
        while (queue.length > 0) {
            const h = queue.pop()!;
            if (out.has(h)) continue;
            out.add(h);
            for (const p of this.stepsByHash.get(h)?.parents ?? []) queue.push(p);
        }
        return out;
    }

    isBelow(a: B64Hash, b: B64Hash): boolean {
        return this.ancestorsOf([b]).has(a);
    }

    descendants(hash: B64Hash): ReleaseInfo[] {
        return this.releases().filter((r) => this.isBelow(hash, r.hash));
    }

    defaultParents(forVersion: string): ReleaseInfo[] {
        const lower = this.releases().filter((r) => compareSemver(r.version, forVersion) < 0);
        if (lower.length === 0) return [];
        const below = this.ancestorsOf(lower.map((r) => r.hash));
        return lower.filter((r) => !below.has(r.hash));
    }

    maximal(hashes: B64Hash[]): B64Hash[] {
        const below = this.ancestorsOf(hashes);
        return hashes.filter((h) => !below.has(h));
    }

    outside(forVersion: string, parents: B64Hash[]): ReleaseInfo[] {
        const past = this.ancestorsOf(parents);
        for (const p of parents) past.add(p);
        return this.releases().filter((r) => compareSemver(r.version, forVersion) < 0 && !past.has(r.hash));
    }

    // Topological steps in the causal closure of `heads`.
    stepsClosure(heads: B64Hash[]): SchemaReleaseStep[] {
        const closure = this.ancestorsOf(heads);
        for (const h of heads) closure.add(h);
        const entries: ReleaseEntry[] = [...closure].map((h) => {
            const step = this.stepsByHash.get(h)!;
            return { hash: step.hash, prevs: [...step.parents].sort(), payload: {} };
        });
        return canonicalEntryOrder(entries).map((e) => this.stepsByHash.get(e.hash)!);
    }

    async base(schemaName: string, parents: B64Hash[]): Promise<SchemaBaseState> {
        if (parents.length === 0) throw new Error('the first release has no base state');
        const closure = this.stepsClosure(parents);
        const ctx = memoryReplica();
        try {
            const signer = await createIdentity(SIGNING_ED25519, ctx.getHashSuite());
            const replayed = await replaySchemaSteps(ctx, schemaName, closure, signer);
            const headEntries = parents.map((p) => replayed.stepToEntry.get(p)!);
            const view = await replayed.schema.getView(versionOf(...headEntries));
            const tables = new Map<string, TableDef>(view.getTableNames().map((t) => [t, view.getTable(t)!]));
            const params = new Map<string, SchemaParamDecl>(view.getParams().map((p) => [p.name, p]));
            const model: SchemaModel = {
                name: schemaName,
                creators: [],
                params,
                tables,
                origin: { kind: 'inline' },
            };
            const steps = new Map(closure.map((s) => [s.hash, s]));
            return {
                parents: sortReleases(parents.map((p) => this.infos.get(p)!)),
                steps,
                view,
                params,
                tables,
                model,
            };
        } finally {
            await ctx.destroy();
        }
    }
}

export type SchemaReleaseDraft = {
    schema: string;
    version: string;
    parents: ReleaseInfo[];
    first: boolean;
    rules: DraftRule[];
    params: SchemaParamDecl[];
    warnings: string[];
    refusals: Refusal[];
    desired: SchemaModel;
    base?: SchemaBaseState;
};

export async function draftSchemaRelease(inputs: {
    schema: string;
    version: string;
    parents: ReleaseInfo[];
    released: ReleasedSchemas;
    source: ReadSchemaSource;
    nextText: string | undefined;
}): Promise<SchemaReleaseDraft> {
    const { schema, version, parents, released, source } = inputs;
    const desired = source.model;
    const plan: SchemaReleaseDraft = {
        schema,
        version,
        parents,
        first: parents.length === 0,
        rules: [],
        params: [],
        warnings: [],
        refusals: [],
        desired,
    };
    const refuse = (message: string, extra: { hint?: string; where?: Where } = {}) => plan.refusals.push({ message, ...extra });

    if (!isValidSemver(version)) refuse(`'${version}' is not a version (major.minor.patch)`);
    else if (isPatchVersion(version)) refuse(`'${version}': ${PATCH_VERSION_RESERVED}`);
    for (const parent of parents) {
        if (isValidSemver(version) && compareSemver(version, parent.version) <= 0) {
            refuse(`${version} is not above its parent ${describeRelease(parent)}`);
        }
    }
    const same = released.releases().filter((r) => r.version === version);
    if (same.length > 0) refuse(`release ${version} already exists (${same.map((r) => r.tag).join(', ')})`);
    if (plan.first && released.releases().length > 0) {
        refuse(`every release after the first has parents, and no release is below ${version}`);
    }
    if (plan.refusals.length > 0) return plan;

    if (plan.first) {
        if (!isBlankSql(inputs.nextText)) {
            refuse(`${UPGRADE_MANUAL_FILE} alters the parents, and the first release has none: leave it empty`);
            return plan;
        }
        plan.params = [...(desired.params?.values() ?? [])];
        const ctx = memoryReplica();
        try {
            const signer = await createIdentity(SIGNING_ED25519, ctx.getHashSuite());
            const stepBody: Omit<SchemaReleaseStep, 'hash'> = {
                parents: [],
                version,
                ...(plan.params.length > 0 ? { params: plan.params } : {}),
                tables: [...desired.tables.values()],
            };
            const hash = schemaStepHash(schema, stepBody);
            await replaySchemaSteps(ctx, schema, [{ hash, ...stepBody }], signer);
        } catch (err) {
            refuse(err instanceof Error ? err.message : String(err), at(source.locate(unitKey.schema(schema))));
        } finally {
            await ctx.destroy();
        }
        return plan;
    }

    const base = await released.base(schema, parents.map((p) => p.hash));
    plan.base = base;

    let hand;
    try {
        hand = readNext(
            inputs.nextText ?? '',
            (name) => (name === schema ? base.view : undefined),
            UPGRADE_MANUAL_FILE,
            (name) => (name === schema && desired.params !== undefined ? new Set(desired.params.keys()) : undefined),
        );
    } catch (err) {
        if (!(err instanceof SourceError)) throw err;
        for (const issue of err.issues) refuse(issue.message, { ...at(issue.where) });
        return plan;
    }

    const where = at(source.locate(unitKey.schema(schema)));
    const paramDiff = diffSchemaParams(schema, base.params, desired.params, (p) => source.locate(unitKey.schemaParam(schema, p)) ?? where.where);
    if (paramDiff.refusals.length > 0) {
        plan.refusals.push(...paramDiff.refusals);
        return plan;
    }

    const paramTypes = new Map<string, ColumnType>();
    for (const [pName, decl] of base.params) paramTypes.set(pName, decl.type);
    for (const decl of paramDiff.added) paramTypes.set(decl.name, decl.type);
    const resolveParam = (pName: string) => paramTypes.get(pName);

    const handRules = hand.rules.get(schema) ?? [];
    const working = new Map(base.tables);
    const applied = applyMigrationRules(working, handRules.map((h) => h.rule), resolveParam);
    if (!applied.ok) {
        refuse(`ALTER SCHEMA ${schema}: ${applied.reason}`, { ...at(handRules[applied.index]?.where) });
        return plan;
    }

    const diff = diffTables(schema, working, desired.tables, {
        table: (t) => source.locate(unitKey.table(schema, t)),
        column: (t, c) => source.locate(unitKey.column(schema, t, c)),
    });
    if (diff.refusals.length > 0) {
        plan.refusals.push(...diff.refusals);
        return plan;
    }

    const rules: DraftRule[] = [...handRules.map((h) => ({ rule: h.rule, where: h.where })), ...diff.rules.map((rule) => ({ rule }))];
    if (rules.length === 0 && paramDiff.added.length === 0) {
        refuse(parents.length === 1
            ? `nothing to release: ${SCHEMA_SOURCE_FILE} and ${UPGRADE_MANUAL_FILE} describe ${describeRelease(parents[0])} as it is`
            : `nothing to release: ${SCHEMA_SOURCE_FILE} and ${UPGRADE_MANUAL_FILE} add no migration rules or parameters to the parents' merge; a schema step must change something`);
        return plan;
    }

    const simulated = new Map(base.tables);
    const check = applyMigrationRules(simulated, rules.map((r) => r.rule), resolveParam);
    const left = check.ok ? tableDifferences(schema, simulated, desired.tables) : [];
    if (!check.ok || left.length > 0) {
        throw new Error(`the generated rules for ${schema} don't reach ${SCHEMA_SOURCE_FILE}: `
            + (check.ok ? left.join('; ') : `rule ${check.index + 1} is refused: ${check.reason}`));
    }

    plan.rules = rules;
    plan.params = paramDiff.added;

    const highest = parents.reduce((a, b) => (compareSemver(a.version, b.version) >= 0 ? a : b));
    const major = (v: string) => parseSemver(v)?.major ?? 0;
    const lost = rules.filter((r) => isBreaking(r.rule) && r.rule.rule !== 'add-table' && base.tables.has(r.rule.table));
    if (lost.length > 0 && major(version) <= major(highest.version)) {
        plan.warnings.push(`${schema} ${lost.map((r) => describeBreaking(r.rule)).join(', ')}, and ${version} is not a major bump from ${highest.version}`);
    }
    for (const lower of released.outside(version, parents.map((p) => p.hash))) {
        const including = released.maximal([...parents.map((p) => p.hash), lower.hash]);
        const selectors = including.map((h) => released.get(h)!.version).join(' + ');
        plan.warnings.push(`${describeRelease(lower)} is below ${version} and not in its past: an instance running it would run it alongside ${version}`
            + ` (\`rpack set base ${selectors}\` includes it)`);
    }

    return plan;
}

function at(where: Where | undefined): { where?: Where } {
    return where === undefined ? {} : { where };
}

function describeBreaking(rule: MigrationRule): string {
    switch (rule.rule) {
        case 'drop-table': return `drops table ${rule.table}`;
        case 'drop-column': return `drops column ${rule.table}.${rule.column}`;
        case 'set-fks': return `changes the foreign keys of ${rule.table}`;
        case 'set-restrictions': return `changes the restrictions of ${rule.table}`;
        case 'set-concurrent-deletes': return `changes the concurrent deletes of ${rule.table}`;
        default: return rule.rule;
    }
}

export function formatSchemaDraftSql(plan: SchemaReleaseDraft): string[] {
    if (plan.refusals.length > 0) return [];
    const quote = (v: string) => renderLiteral(v);
    if (plan.first) {
        const params = plan.desired.params !== undefined && plan.desired.params.size > 0
            ? [...plan.desired.params.values()]
            : undefined;
        const rendered = renderSourceSchema({
            name: plan.schema,
            creators: [],
            ...(params !== undefined ? { params } : {}),
            ...(plan.desired.hashAlgorithm !== undefined ? { hashAlgorithm: plan.desired.hashAlgorithm } : {}),
            tables: [...plan.desired.tables.values()],
        });
        const versionClause = ` VERSION ${quote(plan.version)}`;
        const withVer = rendered.includes(' PARAMS (')
            ? rendered.replace(' PARAMS (', `${versionClause} PARAMS (`)
            : rendered.includes(' HASH ALGORITHM ')
                ? rendered.replace(' HASH ALGORITHM ', `${versionClause} HASH ALGORITHM `)
                : rendered.replace(/ AS \(\n/, `${versionClause} AS (\n`);
        return withVer.split('\n');
    }

    const paramsClause = plan.params.length > 0 ? ` ${renderSchemaParamDecls(plan.params)}` : '';
    if (plan.rules.length === 0) {
        return [`ALTER SCHEMA ${renderIdent(plan.schema)} VERSION ${quote(plan.version)}${paramsClause};`];
    }
    const rules = plan.rules.map((r, i) => {
        const separator = i < plan.rules.length - 1 ? ',' : '';
        const comment = r.where !== undefined ? `    -- ${r.where.file}:${r.where.line}` : '';
        return `  ${renderMigrationRule(r.rule)}${separator}${comment}`;
    });
    return [`ALTER SCHEMA ${renderIdent(plan.schema)} VERSION ${quote(plan.version)}${paramsClause} AS (`, ...rules.join('\n').split('\n'), ');'];
}

export function formatSchemaUpgrade(plan: SchemaReleaseDraft): string {
    return `${SCHEMA_UPGRADE_HEADER}\n\n${formatSchemaDraftSql(plan).join('\n')}\n`;
}

export function formatSchemaDraft(plan: SchemaReleaseDraft): string[] {
    const lines: string[] = [];
    const from = plan.first ? 'the first release' : `from ${plan.parents.map(describeRelease).join(' + ')}`;
    lines.push(`${plan.schema} ${plan.version}, ${from}`);

    if (plan.refusals.length > 0) {
        lines.push('', 'refused');
        for (const refusal of plan.refusals) {
            lines.push(`  ${formatWhere(refusal.where)}${refusal.message}`);
            if (refusal.hint !== undefined) lines.push(`    ${refusal.hint}`);
        }
        return lines;
    }

    lines.push('', ...formatSchemaDraftSql(plan));

    if (plan.warnings.length > 0) {
        lines.push('', 'warnings');
        for (const warning of plan.warnings) lines.push(`  ${warning}`);
    }
    return lines;
}

export type ProducedSchemaRelease = {
    hash: B64Hash;
    version: string;
    name: string;
    file: SchemaReleaseFile;
    text: string;
};

export async function produceSchemaRelease(
    draft: SchemaReleaseDraft,
    released: ReleasedSchemas,
    options: { note?: string } = {},
): Promise<ProducedSchemaRelease> {
    if (draft.refusals.length > 0) {
        throw new Error(`the draft has refusals:\n${draft.refusals.map((r) => r.message).join('\n')}`);
    }

    const parentHashes = draft.parents.map((p) => p.hash).sort();
    const stepBody: Omit<SchemaReleaseStep, 'hash'> = draft.first
        ? {
            parents: [],
            version: draft.version,
            ...(draft.params.length > 0 ? { params: draft.params } : {}),
            tables: [...draft.desired.tables.values()],
            ...(options.note !== undefined ? { note: options.note } : {}),
        }
        : {
            parents: parentHashes,
            version: draft.version,
            ...(draft.params.length > 0 ? { params: draft.params } : {}),
            ...(draft.rules.length > 0 ? { migration: draft.rules.map((r) => r.rule) } : {}),
            ...(options.note !== undefined ? { note: options.note } : {}),
        };

    const hash = schemaStepHash(draft.schema, stepBody);
    const step: SchemaReleaseStep = { hash, ...stepBody };
    const priorSteps = draft.first ? [] : released.stepsClosure(parentHashes);
    const steps = [...priorSteps, step];

    const file: SchemaReleaseFile = {
        format: 1,
        manifest: {
            kind: 'schema',
            name: draft.schema,
            version: draft.version,
            release: hash,
            parents: parentHashes,
            ...(options.note !== undefined ? { note: options.note } : {}),
        },
        steps,
    };

    const text = serializeReleaseFile(file);
    const verified = await verifyRelease(text);
    if (!verified.ok) {
        throw new Error(`the produced schema release failed verification (a bug in rpack): ${verified.problems.join('; ')}`);
    }

    released.addStep(draft.schema, step);
    const after = await released.base(draft.schema, [hash]);
    const diff = [
        ...paramDifferences(draft.schema, after.params, draft.desired.params),
        ...tableDifferences(draft.schema, after.tables, draft.desired.tables),
    ];
    if (diff.length > 0) {
        throw new Error(`the produced schema release does not match ${SCHEMA_SOURCE_FILE} (a bug in rpack): ${diff.join('; ')}`);
    }

    return {
        hash,
        version: draft.version,
        name: releaseName(draft.schema, draft.version, hash),
        file,
        text,
    };
}

export function renderSchemaSource(target: SchemaModel): string {
    const params = target.params !== undefined && target.params.size > 0
        ? [...target.params.values()]
        : undefined;
    return `${renderSourceSchema({
        name: target.name,
        creators: [],
        ...(params !== undefined ? { params } : {}),
        ...(target.hashAlgorithm !== undefined ? { hashAlgorithm: target.hashAlgorithm } : {}),
        tables: [...target.tables.values()],
    })}\n`;
}
